// Prints SQL INSERTs for the curated challenge set (first cycle), ready for the Supabase SQL editor:
//   node scripts/generate-seed.mjs > supabase/seed.sql
import fs from "node:fs";

const defs = JSON.parse(fs.readFileSync(new URL("../src/lib/data/challenges.json", import.meta.url), "utf8"));
const LAUNCH = "2026-10-22"; // keep in sync with LAUNCH_DATE in src/lib/data/challenges.ts
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;
const dateFor = (i) => {
  const d = new Date(`${LAUNCH}T12:00:00Z`);
  d.setUTCDate(d.getUTCDate() + i);
  return d.toISOString().slice(0, 10);
};

console.log("-- Generated by scripts/generate-seed.mjs — do not edit by hand.");
console.log("insert into public.challenges (id, number, publish_date, slug, subject, answer, alternatives, nudges, category, difficulty, fact, stage_images, credit) values");
console.log(
  defs
    .map((d, i) => {
      const n = i + 1;
      const id = `sig-${String(n).padStart(3, "0")}`;
      // opaque storage paths (never the subject name); upload with scripts/upload-stages.mjs
      const stages = [1, 2, 3, 4, 5].map((s) => `${id}/stage-${s}.webp`);
      return `  (${q(id)}, ${n}, ${q(dateFor(i))}, ${q(d.slug)}, ${q(d.subject)}, ${q(d.answer)}, ${arr(d.alternatives)}, ${arr(d.nudges)}, ${q(d.category)}, ${q(d.difficulty)}, ${q(d.fact)}, ${arr(stages)}, ${q(JSON.stringify(d.credit))}::jsonb)`;
    })
    .join(",\n") + "\non conflict (id) do nothing;",
);
